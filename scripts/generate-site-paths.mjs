// Generator: src/data/site-paths.ts — daftar path valid untuk middleware 404
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const valid = new Set();

// 1. Static app routes (semua rute tetap + ads/metaads/landing/thankyou yang 200)
const staticRoutes = [
  '', '/news-blog', '/panduan', '/about-us', '/about-us/alur-maklon',
  '/services', '/contact-us', '/contact-medsos', '/our-client', '/career',
  '/terms-of-service', '/privacy-policy', '/estimasi-biaya-maklon-kosmetik',
  '/biaya-maklon-skincare', '/moq-maklon-kosmetik', '/jasa-maklon-kosmetik',
  '/private-label-kosmetik', '/lead-test', '/landing/mof-bof',
  // Ads landing (200 untuk tracking, noindex)
  '/ads/maklon-body-care', '/ads/maklon-hair-care', '/ads/maklon-parfum', '/ads/maklon-skincare',
  '/ads/thankyou/google', '/ads/thankyou/google-ads', '/ads/thankyou/metaads', '/ads/thankyou-medsos',
  // Google Ads / Meta Ads landing
  '/google-ads/maklon-body-care', '/google-ads/maklon-hair-care',
  '/google-ads/maklon-kosmetik', '/google-ads/maklon-parfum',
  '/metaads/babycare', '/metaads/deodorant', '/metaads/haircare',
  '/metaads/parfum', '/metaads/skincare',
  '/hair-care/metaads', '/parfum/metaads', '/skincare-face-care/metaads',
  // Thankyou (200 untuk tracking, noindex)
  '/thankyou/google', '/thankyou-medsos',
  '/panduan/cara-menentukan-moq-produk-kosmetik',
  '/panduan/komponen-biaya-maklon-skincare',
  '/category/maklon-kosmetik', '/category/panduan-bisnis-kosmetik',
  '/category/dreampreneur-beauty-academy', '/category/dreamlabpedia',
  // Halaman hub /produk/ (katalog produk — breadcrumb semua halaman produk menunjuk ke sini)
  '/produk',
  '/en', '/en/produk', '/en/about-us', '/en/services', '/en/our-client', '/en/contact-us',
];
staticRoutes.forEach(r => valid.add(r.replace(/^\/+/, '').replace(/\/+$/, '')));

// 2. Artikel
const articlesSrc = fs.readFileSync(path.join(root, 'src/data/articles.ts'), 'utf-8');
for (const m of articlesSrc.matchAll(/"slug":\s*"([^"]+)"/g)) {
  valid.add(m[1].replace(/^\/+/, '').replace(/\/+$/, ''));
}

// 3. Maklon pages — FASE 2: semua /maklon-* product page kini 301 ke /produk/*
//   (via MAKLON_PRODUCT_REDIRECTS di proxy.ts), jadi JANGAN masuk SITE_PATHS.
//   Jika redirect terlewat, path akan 404 (aman) bukan serve duplikat.
//   Catatan: artikel standalone bernama maklon-* (dari articles.ts) tetap valid
//   karena diambil dari daftar artikel, bukan dari sini.
const maklonSrc = fs.readFileSync(path.join(root, 'src/data/maklon-pages.ts'), 'utf-8');
for (const m of maklonSrc.matchAll(/path:\s*['"]([^'"]+)['"]/g)) {
  const p = m[1].replace(/^\/+/, '').replace(/\/+$/, '');
  if (!p.startsWith('maklon-')) valid.add(p);
}

// 4. seo-mapping destinations (redirect target valid)
const mapping = JSON.parse(fs.readFileSync(path.join(root, 'src/data/seo-mapping.json'), 'utf-8'));
for (const m of mapping) {
  if (m.destination) valid.add(m.destination.replace(/^\/+/, '').replace(/\/+$/, ''));
}

// 5. CSV programmatic slugs
const csv = fs.readFileSync(path.join(root, 'src/data/seo-audit-export.csv'), 'utf-8').split('\n').slice(1);
for (const line of csv) {
  const cols = line.split(',');
  if (cols.length < 2) continue;
  const slug = cols[1].replace(/^"|"$/g, '').trim().replace(/^\/+/, '').replace(/\/+$/, '');
  if (!slug || slug === '/') continue;
  if (slug.includes('%20') || slug.includes(' ')) continue;
  valid.add(slug);
}

// 6. Produk pages (dari products-v2)
const prodFiles = fs.readdirSync(path.join(root, 'src/data/products-v2')).filter(f => f.endsWith('.ts') && f !== 'index.ts');
for (const f of prodFiles) {
  const cat = f.replace('.ts', '');
  const src = fs.readFileSync(path.join(root, 'src/data/products-v2', f), 'utf-8');
  valid.add(`produk/${cat}`);
  for (const m of src.matchAll(/slug:\s*['"]([^'"]+)['"]/g)) {
    valid.add(`produk/${cat}/${m[1]}`);
  }
}

// 7. author & news-blog pagination (valid)
valid.add('author/admin');
for (let i = 2; i <= 12; i++) {
  valid.add(`author/admin/page/${i}`);
  valid.add(`news-blog/page/${i}`);
  valid.add(`page/${i}`);
}

// Hapus kosong, urutkan
const list = Array.from(valid).filter(Boolean).sort();
const out = `// GENERATED by scripts/generate-site-paths.mjs — DO NOT EDIT MANUALLY.
// Daftar path SAH untuk middleware 404 (proxy.ts). Regenerate: npm run gen:paths
export const SITE_PATHS: string[] = ${JSON.stringify(list, null, 2)};
`;
fs.writeFileSync(path.join(root, 'src/data/site-paths.ts'), out, 'utf-8');
console.log('Generated', list.length, 'valid paths -> src/data/site-paths.ts');
