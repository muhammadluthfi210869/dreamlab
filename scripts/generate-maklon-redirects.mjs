// Generator: src/data/maklon-redirects.ts — mapping redirect maklon → /produk/
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const catMap = {
  'maklon-body-care': 'bodycare', 'maklon-hair-care': 'haircare',
  'maklon-decorative': 'decorative', 'maklon-foot-care': 'footcare',
  'maklon-skincare': 'skincare', 'maklon-parfum': 'parfum',
  'maklon-baby-care': 'babycare', 'maklon-pkrt': 'pkrt',
};

// Variasi slug yang TIDAK 1:1 (manual override)
const slugVar = {
  'skincare/masker-wajah': 'face-mask',
  'skincare/serum-wajah': 'facial-serum',
  'skincare/cleansing-series': 'cleansing',
  'bodycare/sabun-antibakteri': 'anti-bacterial-soap',
  'bodycare/sabun-batang': 'bar-soap',
  'bodycare/sabun-organik': 'organic-soap',
  'bodycare/sabun-transparan': 'transparent-soap',
  'bodycare/sabun-whitening': 'whitening-soap',
  'babycare/baby-moisturizer': 'baby-lotion',
  'decorative/highlighter': 'liquid-highlighter',
};

// Mapping DECORATIVE lengkap (terverifikasi terhadap rute /produk/decorative/*).
// Kategori ini struktur campuran (flat + sub-kategori). Produk yang punya halaman
// FLAT (/produk/decorative/{produk}/) → arahkan ke flat (kanonis, ada di sitemap).
// Produk yang hanya ada di sub-kategori (/produk/decorative/{make-up|lipcare}/{produk}/)
// → arahkan ke halaman produk sub-kategori (sekarang 200 — SITE_PATHS sudah fix).
// Produk tanpa halaman individual → sub-kategori induk.
const decorativeFallback = {
  // ===== makeup/* =====
  'makeup/cream-blush': '/produk/decorative/cream-blush/',        // flat
  'makeup/mascara': '/produk/decorative/mascara/',                // flat
  'makeup/highlighter': '/produk/decorative/liquid-highlighter/', // flat
  'makeup/foundation': '/produk/decorative/make-up/foundation/',  // sub-cat only
  'makeup/bb-cream': '/produk/decorative/make-up/bb-cream/',      // sub-cat only
  'makeup/face-primer': '/produk/decorative/make-up/face-primer/',
  'makeup/eyebrow-gel': '/produk/decorative/make-up/eyebrow-gel/',
  'makeup/liquid-blush': '/produk/decorative/make-up/liquid-blush/',
  'makeup/foundation-serum': '/produk/decorative/make-up/foundation-serum/',
  // ===== lip-care/* =====
  'lip-care/lip-gloss': '/produk/decorative/lip-gloss/',          // flat
  'lip-care/lip-matte': '/produk/decorative/lip-matte/',          // flat
  'lip-care/lip-cream': '/produk/decorative/lipcare/lip-cream/',  // sub-cat only
  'lip-care/lip-serum': '/produk/decorative/lipcare/lip-serum/',
  'lip-care/lip-balm': '/produk/decorative/lipcare/lip-balm/',
  'lip-care/tinted-lip-balm': '/produk/decorative/lipcare/tinted-lip-balm/',
  'lip-care/lip-scrub': '/produk/decorative/lipcare/lip-scrub/',
  'lip-care/lip-blush': '/produk/decorative/lipcare/',            // TIDAK ada halaman individual
  // ===== parents =====
  'makeup': '/produk/decorative/make-up/',
  'lip-care': '/produk/decorative/lipcare/',
};

// Load produk slugs per category
function loadSlugs(cat) {
  const src = fs.readFileSync(path.join(root, `src/data/products-v2/${cat}.ts`), 'utf-8');
  return new Set([...src.matchAll(/slug:\s*['"]([^'"]+)['"]/g)].map(m => m[1]));
}

// Load maklon pages
const maklonSrc = fs.readFileSync(path.join(root, 'src/data/maklon-pages.ts'), 'utf-8');
const maklonPaths = [...maklonSrc.matchAll(/path:\s*['"]([^'"]+)['"]/g)].map(m => m[1].replace(/^\/|\/$/g, ''));

const mapping = {};
// Parents
for (const [prefix, prodCat] of Object.entries(catMap)) {
  mapping[`/${prefix}/`] = `/produk/${prodCat}/`;
}
// Sub-pages
for (const p of maklonPaths) {
  const parts = p.split('/');
  if (parts.length < 2) continue;
  const [prefix, ...sub] = parts;
  if (!catMap[prefix]) continue;
  const prodCat = catMap[prefix];
  const subKey = sub.join('/');
  const fullKey = `${prodCat}/${subKey}`;

  // Fallback decorative khusus (hardcoded — struktur campuran)
  if (prefix === 'maklon-decorative') {
    const decoKey = subKey;
    const target = decorativeFallback[decoKey];
    if (target) {
      mapping[`/${p}/`] = target;
    } else {
      mapping[`/${p}/`] = `/produk/${prodCat}/`;
    }
    continue;
  }

  // Variasi slug manual
  if (slugVar[fullKey]) {
    mapping[`/${p}/`] = `/produk/${prodCat}/${slugVar[fullKey]}/`;
    continue;
  }

  // Cek slug langsung di produk kategori
  const slugs = loadSlugs(prodCat);
  if (slugs.has(subKey)) {
    mapping[`/${p}/`] = `/produk/${prodCat}/${subKey}/`;
  }
  // Jika tidak, fallback ke kategori parent
  else {
    mapping[`/${p}/`] = `/produk/${prodCat}/`;
  }
}
// Hapus pkrt (di-410 via GONE_PATTERNS)
delete mapping['/maklon-pkrt/'];

const lines = [
  '// GENERATED by scripts/generate-maklon-redirects.mjs — DO NOT EDIT MANUALLY.',
  '// Redirect 301 halaman produk maklon → /produk/*. Regenerate: npm run gen:paths',
  'export const MAKLON_PRODUCT_REDIRECTS: Record<string, string> = {',
];
for (const k of Object.keys(mapping).sort()) {
  lines.push(`  "${k}": "${mapping[k]}",`);
}
lines.push('};', '');
fs.writeFileSync(path.join(root, 'src/data/maklon-redirects.ts'), lines.join('\n'), 'utf-8');
console.log(`Generated ${Object.keys(mapping).length} maklon redirects`);
